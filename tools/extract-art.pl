#!/usr/bin/env perl
# Extracts the ASCII art from the original Perl asciiquarium into src/art.h,
# so the C port draws exactly the same pictures. Every q{...} and q#...#
# literal is found in source order and evaluated by Perl itself, which
# matters: q{} turns "\\" into "\", and the fish are full of backslashes.
#
# Only needed when the art changes; src/art.h is committed, so building
# the game needs no Perl.
#   perl tools/extract-art.pl asciiquarium > src/art.h
use strict;
use warnings;

my $src = do { local $/; <> };

# literals in the order they appear in the original, with their names
my @names = (
	(map { "water_line_segment_$_" } 0..3),
	'castle_image', 'castle_mask',
	(map { "fish_$_" } 0..31),                 # image, mask, image, mask ...
	(map { "splat_$_" } 0..3),
	'shark_image_0', 'shark_image_1', 'shark_mask_0', 'shark_mask_1',
	'hook_image', 'point_image',
	'ship_image_0', 'ship_image_1', 'ship_mask_0', 'ship_mask_1',
	'whale_image_0', 'whale_image_1', 'whale_mask_0', 'whale_mask_1',
	(map { "water_spout_$_" } 0..6),
	(map { "monster_0_$_" } 0..3), (map { "monster_1_$_" } 0..3),
	'monster_mask_0', 'monster_mask_1',
	'big_fish_image_0', 'big_fish_image_1', 'big_fish_mask_0', 'big_fish_mask_1',
	(map { "duck_0_$_" } 0..2), (map { "duck_1_$_" } 0..2),
	'duck_mask_0', 'duck_mask_1',
	'dolphin_0_0', 'dolphin_0_1', 'dolphin_1_0', 'dolphin_1_1',
	'dolphin_mask_0', 'dolphin_mask_1',
	'swan_image_0', 'swan_image_1', 'swan_mask_0', 'swan_mask_1',
);

my @lits;
while ($src =~ /\bq([{#])/g) {
	my ($open, $start) = ($1, pos($src));
	my ($i, $depth) = ($start, 1);
	while ($i < length $src) {
		my $c = substr($src, $i, 1);
		if ($c eq '\\') { $i += 2; next; }
		if ($open eq '{') {
			$depth++ if $c eq '{';
			$depth-- if $c eq '}';
			last if $depth == 0;
		} elsif ($c eq '#') {
			last;
		}
		$i++;
	}
	my $close = $open eq '{' ? '}' : '#';
	my $body = substr($src, $start, $i - $start);
	my $value = eval "q$open$body$close";
	die "cannot evaluate literal at offset $start: $@" if $@;
	my $line = 1 + (substr($src, 0, $start) =~ tr/\n//);
	push @lits, [ $line, $value ];
	pos($src) = $i + 1;
}

die sprintf("expected %d literals, found %d\n", scalar @names, scalar @lits)
	unless @lits == @names;

sub c_string {
	my ($s) = @_;
	my @parts;
	for my $line (split /(?<=\n)/, $s) {
		(my $e = $line) =~ s/([\\"])/\\$1/g;
		$e =~ s/\n/\\n/g;
		$e =~ s/\?/\\?/g;          # no trigraphs: every ? as \?
		push @parts, qq{\t"$e"};
	}
	@parts = (qq{\t""}) unless @parts;
	return join("\n", @parts);
}

print "/* Generated by tools/extract-art.pl from the original asciiquarium 1.1\n";
print " * (Perl) by Kirk Baucom; most of the art by Joan Stark. Do not edit:\n";
print " * change the original and regenerate. GPL-2.0-or-later. */\n\n";
for my $n (0..$#names) {
	my ($line, $value) = @{ $lits[$n] };
	print "/* asciiquarium line $line */\n";
	print "static const char $names[$n]\[] =\n", c_string($value), ";\n\n";
}
